internal enum class GlassMaterialRole { Control, Section, MediaOverlay }

/** Foregrounds belong to the material, rather than to the app's light/dark preference. */
@Immutable
internal data class GlassContentColors(val primary: Color, val secondary: Color, val plate: Color,
    val tint: Float = 0f) {
    companion object {
        val light = GlassContentColors(Color(0xFFF9FAFF), Color(0xFFF0F3FC), GlassOptics.darkPlate)
        val dark = GlassContentColors(Color(0xFF101827), Color(0xFF172235), Color.White)
    }
}

@Immutable
internal data class GlassSceneContrast(val average: Color, val darkest: Color, val brightest: Color,
    val sampled: Boolean, val bounded: Boolean = false)

internal val LocalGlassScene = staticCompositionLocalOf<GlassScene?> { null }
internal val LocalGlassContentColors = staticCompositionLocalOf { GlassContentColors.light }
internal val LocalGlassMotionEnabled = staticCompositionLocalOf { true }
internal val LocalInsideGlassSection = staticCompositionLocalOf { false }

/** One bounded spatial sample per scene, shared by every consumer. No control reads pixels. */
@Stable
internal class GlassScene(val backdrop: LayerBackdrop, val seed: Color) {
    internal val changed = Channel<Unit>(Channel.CONFLATED)
    internal var bounds = Rect.Zero
    internal var samples by mutableStateOf<IntArray?>(null)
    internal var generated by mutableStateOf<List<Color>?>(null)
    internal var contentRange by mutableStateOf<Pair<Color, Color>?>(null)
    internal var captures = 0
    internal fun invalidate() { changed.trySend(Unit) }

    fun backgroundAt(target: Rect): Color = contrastAt(target).average

    fun contrastAt(target: Rect): GlassSceneContrast {
        generated?.takeIf { it.isNotEmpty() }?.let { colors ->
            return GlassSceneContrast(Color(colors.map { it.red }.average().toFloat(),
                colors.map { it.green }.average().toFloat(), colors.map { it.blue }.average().toFloat()),
                contentRange?.first ?: Color.Black, contentRange?.second ?: Color.White, true,
                bounded = contentRange != null)
        }
        val pixels = samples ?: return GlassSceneContrast(seed,
            contentRange?.first ?: seed, contentRange?.second ?: seed,
            sampled = contentRange != null, bounded = contentRange != null)
        if (bounds.isEmpty || target.isEmpty) return GlassSceneContrast(seed, seed, seed, false)
        val left = (((target.left - bounds.left) / bounds.width) * WIDTH).toInt().coerceIn(0, WIDTH - 1)
        val right = (((target.right - bounds.left) / bounds.width) * WIDTH).toInt().coerceIn(left + 1, WIDTH)
        val top = (((target.top - bounds.top) / bounds.height) * HEIGHT).toInt().coerceIn(0, HEIGHT - 1)
        val bottom = (((target.bottom - bounds.top) / bounds.height) * HEIGHT).toInt().coerceIn(top + 1, HEIGHT)
        var red = 0L; var green = 0L; var blue = 0L; var count = 0
        var darkest = Color.White; var brightest = Color.Black
        var darkestLuma = 1f; var brightestLuma = 0f
        for (y in top until bottom) for (x in left until right) {
            val pixel = pixels[y * WIDTH + x]
            red += (pixel shr 16) and 255; green += (pixel shr 8) and 255; blue += pixel and 255; count++
            val color = Color(pixel)
            val luminance = LINEAR[(pixel shr 16) and 255] * .2126f +
                LINEAR[(pixel shr 8) and 255] * .7152f + LINEAR[pixel and 255] * .0722f
            if (luminance < darkestLuma) { darkest = color; darkestLuma = luminance }
            if (luminance > brightestLuma) { brightest = color; brightestLuma = luminance }
        }
        return if (count == 0) GlassSceneContrast(seed, seed, seed, false) else GlassSceneContrast(
            Color(red.toFloat() / count / 255, green.toFloat() / count / 255, blue.toFloat() / count / 255),
            contentRange?.first ?: darkest, contentRange?.second ?: brightest, true, bounded = contentRange != null)
    }

    companion object {
        const val WIDTH = 24; const val HEIGHT = 48; const val INTERVAL_MS = 250L
        private val LINEAR = FloatArray(256) {
            val value = it / 255f
            if (value <= .04045f) value / 12.92f else ((value + .055f) / 1.055f).pow(2.4f)
        }
    }
}

/** Downsample on the GPU before readback: never allocate a full-window bitmap. */
@Composable
internal fun rememberGlassScene(seed: Color = MaterialTheme.colorScheme.surface, samplingEnabled: Boolean = true,
    environmentOnly: Boolean = false,
    sourceDraw: (androidx.compose.ui.graphics.drawscope.ContentDrawScope.() -> Unit)? = null): GlassScene {
    val dark = MaterialTheme.colorScheme.background.luminance() < .3f
    val currentSourceDraw by rememberUpdatedState(sourceDraw)
    val backdrop = rememberLayerBackdrop(onDraw = {
        val customDraw = currentSourceDraw
        if (customDraw != null) customDraw()
        else if (environmentOnly) {
            drawRect(seed)
            drawRect(Brush.linearGradient(listOf((if (dark) Color(0xFF155BA0) else Color(0xFF83BFFF)).copy(alpha = .28f),
                (if (dark) Color(0xFF6944AA) else Color(0xFFC2ACF6)).copy(alpha = .18f))))
        } else drawContent()
    })
    val scene = remember(backdrop, seed) { GlassScene(backdrop, seed) }
    val sampleLayer = rememberGraphicsLayer()
    val density = LocalDensity.current
    val direction = androidx.compose.ui.platform.LocalLayoutDirection.current
    val lifecycle = LocalLifecycleOwner.current.lifecycle
    val enabled = samplingEnabled && !LocalReduceTransparency.current && LocalView.current.isHardwareAccelerated
    DisposableEffect(scene) { onDispose { scene.changed.close() } }
    LaunchedEffect(scene, enabled, lifecycle) {
        if (!enabled) return@LaunchedEffect
        lifecycle.repeatOnLifecycle(Lifecycle.State.RESUMED) {
            var lastCapture = 0L
            val buffer = IntArray(GlassScene.WIDTH * GlassScene.HEIGHT)
            for (ignored in scene.changed) {
                delay((GlassScene.INTERVAL_MS - (SystemClock.uptimeMillis() - lastCapture)).coerceAtLeast(0))
                // Consume changes accumulated during the throttle; a settled scene has no timer.
                while (scene.changed.tryReceive().isSuccess) { }
                // Invalidation originates during drawing. Let the recording node finish before reading it.
                withFrameNanos { }
                val sourceSize = backdrop.graphicsLayer.size
                if (sourceSize.width <= 0 || sourceSize.height <= 0) continue
                lastCapture = SystemClock.uptimeMillis()
                try {
                    sampleLayer.record(density, direction, IntSize(GlassScene.WIDTH, GlassScene.HEIGHT)) {
                        scale(GlassScene.WIDTH.toFloat() / sourceSize.width,
                            GlassScene.HEIGHT.toFloat() / sourceSize.height, pivot = Offset.Zero) {
                            drawLayer(backdrop.graphicsLayer)
                        }
                    }
                    val captured = sampleLayer.toImageBitmap().asAndroidBitmap()
                    val bitmap = if (captured.config == android.graphics.Bitmap.Config.HARDWARE)
                        captured.copy(android.graphics.Bitmap.Config.ARGB_8888, false) else captured
                    bitmap.getPixels(buffer, 0, GlassScene.WIDTH, 0, 0, GlassScene.WIDTH, GlassScene.HEIGHT)
                    // Only this fixed 4.5KB snapshot enters state. The scratch buffer/layer are reused.
                    if (scene.samples?.contentEquals(buffer) != true) scene.samples = buffer.copyOf()
                    scene.captures++
                    bitmap.recycle()
                    if (bitmap !== captured) captured.recycle()
                } catch (cancelled: kotlinx.coroutines.CancellationException) { throw cancelled }
                catch (_: IllegalStateException) { /* Keep the last valid colors while a layer is being replaced. */ }
            }
        }
    }
    return scene
}

internal fun Modifier.recordGlassScene(scene: GlassScene): Modifier =
    onGloballyPositioned { scene.bounds = it.boundsInRoot() }.layerBackdrop(scene.backdrop)
        .drawWithContent { drawContent(); scene.invalidate() }

@Immutable
internal data class GlassEnvironmentPalette(val base: Color, val pools: List<Color>)
internal val LocalGlassEnvironmentPalette = staticCompositionLocalOf<GlassEnvironmentPalette?> { null }

private fun environmentPoolAlpha(dark: Boolean) = if (dark) .52f else .42f

/** Each radial light ranges from transparent to its peak opacity, in drawing order. */
private fun environmentRange(palette: GlassEnvironmentPalette, dark: Boolean): Pair<Color, Color> {
    var low = palette.base
    var high = palette.base
    palette.pools.forEach { color ->
        val overLow = color.copy(alpha = environmentPoolAlpha(dark)).compositeOver(low)
        val overHigh = color.copy(alpha = environmentPoolAlpha(dark)).compositeOver(high)
        low = Color(minOf(low.red, overLow.red), minOf(low.green, overLow.green), minOf(low.blue, overLow.blue))
        high = Color(maxOf(high.red, overHigh.red), maxOf(high.green, overHigh.green), maxOf(high.blue, overHigh.blue))
    }
    return low to high
}

@Composable
internal fun glassEnvironmentPalette(): GlassEnvironmentPalette = LocalGlassEnvironmentPalette.current ?: run {
    val dark = MaterialTheme.colorScheme.background.luminance() < .3f
    GlassEnvironmentPalette(MaterialTheme.colorScheme.surface, if (dark)
        listOf(Color(0xFF155BA0), Color(0xFF077B89), Color(0xFF6944AA))
        else listOf(Color(0xFF83BFFF), Color(0xFF8ADBD3), Color(0xFFC2ACF6)))
}

/** Transfer colors across windows, never a graphics-layer reference. */
@Composable
internal fun originatingGlassPalette(): GlassEnvironmentPalette {
    val palette = glassEnvironmentPalette()
    val scene = LocalGlassScene.current
    return palette.copy(base = scene?.backgroundAt(scene.bounds) ?: palette.base)
}

/** Broad, stationary light pools. Changes come from content/navigation, never an idle loop. */
@Composable
internal fun GlassEnvironment(modifier: Modifier = Modifier) {
    val dark = MaterialTheme.colorScheme.background.luminance() < .3f
    val palette = glassEnvironmentPalette()
    val base = palette.base
    val window = androidx.compose.ui.platform.LocalWindowInfo.current.containerSize
    var origin by remember { mutableStateOf(Offset.Zero) }
    Canvas(modifier.clipToBounds().onGloballyPositioned { origin = it.positionInRoot() }.background(base)) {
        val width = maxOf(size.width, window.width.toFloat())
        val height = maxOf(size.height, window.height.toFloat())
        val pools = palette.pools
        val centers = listOf(Offset(width * .06f, height * .10f) - origin,
            Offset(width * .94f, height * .46f) - origin, Offset(width * .12f, height * .88f) - origin)
        val radius = maxOf(width * 1.25f, height * .55f)
        pools.forEachIndexed { index, color ->
            drawCircle(Brush.radialGradient(listOf(color.copy(alpha = environmentPoolAlpha(dark)),
                color.copy(alpha = if (dark) .16f else .10f), Color.Transparent), centers[index], radius),
                radius, centers[index])
        }
    }
}

/** Safe background-only source for page sections and independent popup/dialog windows. */
@Composable
internal fun GlassBackgroundScene(modifier: Modifier = Modifier, content: @Composable BoxScope.() -> Unit) {
    val palette = glassEnvironmentPalette()
    val windowSource = rememberGlassWindowSource()
    val scene = rememberGlassScene(palette.base)
    val dark = MaterialTheme.colorScheme.background.luminance() < .3f
    // Source-over compositing of these lights is bounded component-wise, even
    // where pools overlap. Unlike arbitrary page imagery, this is a known source.
    SideEffect {
        scene.contentRange = environmentRange(palette, dark)
    }
    Box(modifier) {
        GlassEnvironment(Modifier.matchParentSize().clipToBounds().recordGlassScene(scene))
        CompositionLocalProvider(LocalGlassScene provides scene, LocalGlassBackdrop provides scene.backdrop,
            LocalGlassWindowSource provides windowSource,
            LocalContentColor provides MaterialTheme.colorScheme.onSurface,
            LocalGlassEnvironmentPalette provides palette) { content() }
    }
}

internal fun glassContrast(a: Color, b: Color): Float =
    (maxOf(a.luminance(), b.luminance()) + .05f) / (minOf(a.luminance(), b.luminance()) + .05f)

/** Polarity switches atomically with hysteresis; it never fades through gray. */
@Composable
internal fun rememberGlassContentColors(bounds: Rect = Rect.Zero, role: GlassMaterialRole = GlassMaterialRole.Control,
    prominent: Boolean = false): GlassContentColors {
    if (LocalInsideGlassSection.current && role == GlassMaterialRole.Control) return LocalGlassContentColors.current
    if (role == GlassMaterialRole.MediaOverlay) return GlassContentColors.light.copy(plate = GlassOptics.mediaPlate, tint = GlassOptics.mediaTint)
    val scene = LocalGlassScene.current
    val darkTheme = MaterialTheme.colorScheme.background.luminance() < .3f
    val opaque = LocalReduceTransparency.current || !LocalView.current.isHardwareAccelerated || scene == null
    val contrast = scene?.contrastAt(if (bounds.isEmpty) scene.bounds else bounds)
        ?: GlassSceneContrast(MaterialTheme.colorScheme.surface, MaterialTheme.colorScheme.surface, MaterialTheme.colorScheme.surface, false)
    var plate = if (darkTheme) GlassOptics.darkPlate else Color.White
    var tint = if (opaque) 1f else if (role == GlassMaterialRole.Section) GlassOptics.sectionTint(darkTheme)
        else GlassOptics.controlTint(darkTheme, prominent)
    fun material(color: Color) = plate.copy(alpha = tint).compositeOver(color)
    val background = material(contrast.average)
    var light by remember(scene, opaque) { mutableStateOf(darkTheme) }
    val lightContrast = glassContrast(GlassContentColors.light.secondary, background)
    val darkContrast = glassContrast(GlassContentColors.dark.secondary, background)
    SideEffect {
        if (light && darkContrast > lightContrast * 1.18f) light = false
        else if (!light && lightContrast > darkContrast * 1.18f) light = true
    }
    val colors = if (light) GlassContentColors.light else GlassContentColors.dark
    // Keep one continuous material behind the entire control. Never add a separate
    // rectangle around a label or a disc around an icon. Unknown artwork can contain
    // narrow bright/dark bands that escape the coarse sample, so bound it conservatively.
    val worst = if (!contrast.bounded) { if (light) Color.White else Color.Black }
        else if (light) contrast.brightest else contrast.darkest
    if (!opaque && glassContrast(colors.secondary, material(worst)) < 4.8f) {
        plate = colors.plate
        var low = tint; var high = 1f
        repeat(10) {
            val middle = (low + high) / 2
            if (glassContrast(colors.secondary, plate.copy(alpha = middle).compositeOver(worst)) >= 4.8f) high = middle
            else low = middle
        }
        tint = high
    }
    return colors.copy(plate = plate, tint = tint)
}

/** Also remap explicit theme foregrounds used by existing labels, icons and secondary text. */
@Composable
internal fun GlassForeground(colors: GlassContentColors = rememberGlassContentColors(), content: @Composable () -> Unit) {
    val scheme = MaterialTheme.colorScheme
    CompositionLocalProvider(LocalGlassContentColors provides colors, LocalContentColor provides colors.primary) {
        MaterialTheme(colorScheme = scheme.copy(onSurface = colors.primary, onSurfaceVariant = colors.secondary,
            primary = colors.primary, secondary = colors.secondary,
            error = if (colors.primary.luminance() < .3f) Liquid.light.error else Liquid.dark.error), content = content)
    }
}

@Composable
internal fun GlassSection(modifier: Modifier = Modifier, content: @Composable ColumnScope.() -> Unit) {
    var bounds by remember { mutableStateOf(Rect.Zero) }
    val colors = rememberGlassContentColors(bounds, GlassMaterialRole.Section)
    Column(modifier.fillMaxWidth().onGloballyPositioned { bounds = it.boundsInRoot() }
        .glassMaterial(Liquid.card, role = GlassMaterialRole.Section).padding(16.dp)) {
        CompositionLocalProvider(LocalInsideGlassSection provides true) {
            GlassForeground(colors) { Column(verticalArrangement = Arrangement.spacedBy(8.dp), content = content) }
        }
    }
}

/** A material and its actual foreground are one composition contract. */
@Composable
internal fun GlassSurface(modifier: Modifier = Modifier, shape: Shape = Liquid.pill,
    prominent: Boolean = false, role: GlassMaterialRole = GlassMaterialRole.Control,
    interaction: GlassInteraction? = null, content: @Composable BoxScope.() -> Unit) {
    var bounds by remember { mutableStateOf(Rect.Zero) }
    val colors = rememberGlassContentColors(bounds, role, prominent)
    Box(modifier.onGloballyPositioned { bounds = it.boundsInRoot() }
        .glassMaterial(shape, prominent, role, interaction)) {
        GlassForeground(colors) { content() }
    }
}
