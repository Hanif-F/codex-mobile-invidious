    @Test fun everyAttachmentTypeParsesWithoutDiscardingThePost() {
        val single = JSONObject().put("type", "image").put("imageThumbnails", image())
        val photos = PostPage.parse(json(single)).items.single().attachment as PostAttachment.Images
        assertEquals(1280, photos.images.single().width)
        val gallery = JSONObject().put("type", "multiImage").put("images", JSONArray().put(image()).put(image()))
        assertEquals(2, (PostAttachment.parse(gallery) as PostAttachment.Images).images.size)
        assertEquals("abcdefghijk", (PostAttachment.parse(JSONObject("""{"type":"video","videoId":"abcdefghijk","title":"Attached"}""")) as PostAttachment.VideoItem).video.id)
        assertEquals("PLattached", (PostAttachment.parse(JSONObject("""{"type":"playlist","playlistId":"PLattached","title":"List"}""")) as PostAttachment.PlaylistItem).playlist.id)
        val poll = PostAttachment.parse(JSONObject().put("type", "poll").put("totalVotes", 100)
            .put("choices", JSONArray().put(JSONObject().put("text", "Choice").put("image", image())))) as PostAttachment.Poll
        assertEquals(100L, poll.votes); assertEquals(1280, poll.choices.single().image!!.width); assertFalse(poll.quiz)
        val quiz = PostAttachment.parse(JSONObject("""{"type":"quiz","choices":[{"text":"Answer","isCorrect":true}]}""")) as PostAttachment.Poll
        assertTrue(quiz.quiz); assertEquals(true, quiz.choices.single().correct); assertNull(quiz.votes)
        listOf("""{"type":"unknown"}""", """{"type":"image"}""", """{"type":"video","error":"Unavailable"}""", """{"type":"playlist","playlistId":"../invalid"}""").forEach {
            val item = PostPage.parse(json(JSONObject(it))).items.single()
            assertEquals("Post text", item.comment.text); assertEquals(PostAttachment.Unavailable, item.attachment)
        }
    }
