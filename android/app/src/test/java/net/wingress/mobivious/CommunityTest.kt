    @Test fun latePostCommentResponsesCannotCrossTargetsSortsOrAccounts() = runBlocking {
        val scope = CoroutineScope(SupervisorJob() + Dispatchers.Unconfined)
        try {
            var active = context
            val gate = CompletableDeferred<Unit>()
            val controller = CommentsController(scope, { active }, { target, sort, _, _ ->
                if ((target as CommentTarget.Post).id == post && sort == CommentSort.TOP)
                    withContext(NonCancellable) { gate.await() }
                CommentPage(listOf(comment("${target.id}-${sort.apiValue}")))
            }, { it.message.orEmpty() })
            controller.bind(CommentTarget.Post(post, channel)); controller.open()
            controller.sort(CommentSort.NEWEST)
            assertEquals("$post-new", controller.state.value.feed.page.items.single().id)
            controller.bind(CommentTarget.Post("another-post", channel)); controller.open()
            gate.complete(Unit); yield()
            assertEquals("another-post-top", controller.state.value.feed.page.items.single().id)
            active = context.copy(generation = 1); controller.bind(CommentTarget.Post("another-post", channel))
            assertFalse(controller.state.value.open); assertTrue(controller.state.value.feed.page.items.isEmpty())
        } finally { scope.cancel() }
    }
    @Test fun postReplyFailuresPreserveTheirCursorAndRepeatedContinuationsTerminate() {
        val scope = CoroutineScope(SupervisorJob() + Dispatchers.Unconfined)
        try {
            var fail = true
            val tokens = mutableListOf<String>()
            val parent = comment("parent", "replies")
            val controller = CommentsController(scope, { context }, { target, _, token, _ ->
                assertEquals(CommentTarget.Post(post, channel), target); tokens += token
                when (token) {
                    "" -> CommentPage(listOf(parent), count = 20)
                    "replies" -> CommentPage(listOf(comment("r1")), "more+/=%&")
                    else -> if (fail) throw IllegalStateException("Offline") else CommentPage(listOf(comment("r1"), comment("r2")), token)
                }
            }, { it.message.orEmpty() })
            controller.bind(CommentTarget.Post(post, channel)); controller.open(); controller.replies(parent)
            controller.load(true, parent.key)
            assertEquals("more+/=%&", controller.state.value.thread!!.feed.page.continuation)
            assertEquals("Offline", controller.state.value.thread!!.feed.error)
            fail = false; controller.load(true, parent.key)
            assertEquals(listOf("", "replies", "more+/=%&", "more+/=%&"), tokens)
            assertEquals(listOf("r1", "r2"), controller.state.value.thread!!.feed.page.items.map { it.id })
            assertEquals("", controller.state.value.thread!!.feed.page.continuation)
            assertEquals(20L, controller.state.value.feed.page.count)
        } finally { scope.cancel() }
    }
