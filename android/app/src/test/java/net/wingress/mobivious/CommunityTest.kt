    @Test fun videoAndPostCommentControllersRetainIndependentTargetsAndPositions() {
        val scope = CoroutineScope(SupervisorJob() + Dispatchers.Unconfined)
        try {
            val targets = mutableListOf<CommentTarget>()
            val fetch: suspend (CommentTarget, CommentSort, String, ApiContext) -> CommentPage = { target, _, _, _ ->
                targets += target; CommentPage(listOf(comment("a", "replies")))
            }
            val videos = CommentsController(scope, { context }, fetch, { it.message.orEmpty() })
            val posts = CommentsController(scope, { context }, fetch, { it.message.orEmpty() })
            videos.bind("abcdefghijk", true); videos.open(); videos.position(null, CommentPosition(2, 10))
            posts.bind(CommentTarget.Post(post, channel)); posts.open(); posts.replies(posts.state.value.feed.page.items.single())
            posts.position("a", CommentPosition(1, 20)); posts.close(); posts.open()
            assertEquals(CommentTarget.Video("abcdefghijk"), videos.state.value.target)
            assertEquals(CommentPosition(2, 10), videos.state.value.feed.position); assertTrue(videos.state.value.open)
            assertNull(posts.state.value.videoId); assertEquals(CommentPosition(1, 20), posts.state.value.thread!!.feed.position)
            assertEquals(3, targets.size); posts.back(); assertNull(posts.state.value.threadKey)
            videos.bind("abcdefghijk", false); assertTrue(posts.state.value.open)
        } finally { scope.cancel() }
    }
    @Test fun restoredPostRepliesRetryPendingLoadWithoutLosingParentOrMainPosition() {
        val scope = CoroutineScope(SupervisorJob() + Dispatchers.Unconfined)
        try {
            val parent = comment("a", "reply+/=%&")
            val saved = CommentsState(CommentTarget.Post(post, channel), context, feed = CommentFeed(CommentPage(listOf(parent)), loaded = true, position = CommentPosition(2, 10)),
                threadKey = parent.key, threads = mapOf(parent.key to CommentThread(parent, CommentFeed(loading = true))))
            val tokens = mutableListOf<String>()
            val controller = CommentsController(scope, { context }, { _, _, token, _ -> tokens += token; CommentPage(listOf(comment("reply"))) }, { it.message.orEmpty() })
            controller.restore(saved); controller.open()
            assertEquals(listOf("reply+/=%&"), tokens); assertEquals("reply", controller.state.value.thread!!.feed.page.items.single().id)
            assertEquals(CommentPosition(2, 10), controller.state.value.feed.position)
            controller.restore(saved.copy(context = context.copy(generation = 1))); assertNull(controller.state.value.target)
        } finally { scope.cancel() }
    }
