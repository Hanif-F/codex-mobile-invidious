    @Test fun postsRelatedChannelsDetailsAndCommentsUseTheExistingServerContracts() = runBlocking {
        MockWebServer().use { server ->
            server.start(); val address = server.url("/").toString().trimEnd('/')
            val api = InvidiousApi({ address }, { Account("secret", "Viewer", Long.MAX_VALUE, address) })
            server.enqueue(MockResponse().setBody(json().put("continuation", "next+/=%&").toString()))
            assertEquals(post, api.channelPosts(channel).items.single().id)
            val list = server.takeRequest(); assertEquals("/api/v1/channels/$channel/posts", list.path); assertNull(list.getHeader("Authorization"))
            server.enqueue(MockResponse().setBody("""{"relatedChannels":[{"authorId":"$channel","author":"Related"}],"continuation":"next"}"""))
            assertEquals(channel, api.channelRelated(channel, " next+/=%& ").items.single().id)
            val related = server.takeRequest(); assertEquals(" next+/=%& ", related.requestUrl!!.queryParameter("continuation")); assertNull(related.getHeader("Authorization"))
            server.enqueue(MockResponse().setBody(json().toString()))
            val detail = api.post(PostLink(post)); assertEquals(channel, detail.channelId)
            assertEquals("/api/v1/post/$post", server.takeRequest().path)
            server.enqueue(MockResponse().setBody(json().toString())); api.post(PostLink(post, channel))
            assertEquals(channel, server.takeRequest().requestUrl!!.queryParameter("ucid"))
            listOf("", " reply+/=%& ").forEach { token ->
                server.enqueue(MockResponse().setBody("""{"postId":"$post","comments":[{"commentId":"reply","content":"Hello"}],"continuation":"next"}"""))
                assertEquals("reply", api.postComments(CommentTarget.Post(post, detail.channelId), CommentSort.NEWEST, token).items.single().id)
                val comments = server.takeRequest()
                assertEquals("/api/v1/post/$post/comments", comments.requestUrl!!.encodedPath)
                assertEquals(channel, comments.requestUrl!!.queryParameter("ucid")); assertEquals("new", comments.requestUrl!!.queryParameter("sort_by"))
                assertEquals(token.takeIf { it.isNotBlank() }, comments.requestUrl!!.queryParameter("continuation")); assertNull(comments.getHeader("Authorization"))
            }
        }
    }
